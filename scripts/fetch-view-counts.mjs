#!/usr/bin/env node
/**
 * Refresh YouTube view counts into data/view-counts.json.
 *
 * Counts live in their own file, keyed by youtubeId, rather than inside the
 * village files: they change daily, and rewriting a village file to bump a
 * number would churn the diff of every talk, summary included. data.ts joins
 * them onto talks at load time as `viewCount` / `viewCountFetchedAt`.
 *
 * One `yt-dlp --flat-playlist` call per playlist, so the whole archive costs a
 * couple of hundred requests, not thousands. Flat listings report counts
 * rounded to two or three significant figures, which is plenty for ranking.
 * Talks missing from their playlist listing keep whatever count they had.
 *
 *   node scripts/fetch-view-counts.mjs [--conference black-hat,rsa] [--event defcon-33]
 *                                      [--concurrency 4] [--dry-run]
 */
import { execFile } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { promisify } from "node:util";
import { DATA_DIR, parseArgs, readJson, villageFiles, writeJson } from "./lib/util.mjs";

const run = promisify(execFile);
const OUT = path.join(DATA_DIR, "view-counts.json");
const { args } = parseArgs();

const list = (value) =>
  typeof value === "string" ? new Set(value.split(",").map((s) => s.trim()).filter(Boolean)) : null;
const conferences = list(args.conference);
const events = list(args.event);
const concurrency = Math.max(1, Number(args.concurrency) || 4);

const existing = fs.existsSync(OUT) ? readJson(OUT) : { counts: {} };
const counts = { ...(existing.counts ?? {}) };

// Group wanted IDs by playlist: several village files can share one playlist.
const byPlaylist = new Map();
for (const file of villageFiles()) {
  const village = readJson(file);
  if (conferences && !conferences.has(village.conference)) continue;
  if (events && !events.has(village.eventSlug)) continue;
  const ids = byPlaylist.get(village.playlistUrl) ?? new Set();
  for (const talk of village.talks) ids.add(talk.youtubeId);
  byPlaylist.set(village.playlistUrl, ids);
}

async function fetchPlaylist(url) {
  const { stdout } = await run("yt-dlp", ["--flat-playlist", "-J", "--no-warnings", url], {
    maxBuffer: 256 * 1024 * 1024,
  });
  return JSON.parse(stdout).entries ?? [];
}

const queue = [...byPlaylist.entries()];
const fetchedAt = new Date().toISOString();
let updated = 0;
let failed = 0;
let done = 0;

async function worker() {
  for (let next = queue.shift(); next; next = queue.shift()) {
    const [url, ids] = next;
    try {
      for (const entry of await fetchPlaylist(url)) {
        if (!ids.has(entry.id) || !Number.isFinite(entry.view_count)) continue;
        counts[entry.id] = { viewCount: entry.view_count, fetchedAt };
        updated += 1;
      }
    } catch (cause) {
      failed += 1;
      console.warn(`  skip  ${url} (${String(cause.message ?? cause).split("\n")[0]})`);
    }
    done += 1;
    if (done % 10 === 0) console.log(`  ${done}/${byPlaylist.size} playlists`);
  }
}

await Promise.all(Array.from({ length: concurrency }, worker));

console.log(`\n  playlists ${byPlaylist.size} (${failed} failed)`);
console.log(`  counts    ${updated} refreshed, ${Object.keys(counts).length} total`);

if (args["dry-run"]) {
  console.log("  --dry-run: not written\n");
} else {
  const sorted = Object.fromEntries(Object.keys(counts).sort().map((id) => [id, counts[id]]));
  writeJson(OUT, {
    notes: [
      "Generated by scripts/fetch-view-counts.mjs. Keyed by youtubeId; do not hand-edit.",
      "Counts come from YouTube playlist listings and are rounded to 2-3 significant figures.",
    ],
    counts: sorted,
  });
  console.log(`  wrote ${path.relative(process.cwd(), OUT)}\n`);
}
